def _write(out: Path, name: str, content: str) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    path = out / name
    path.write_text(content, encoding="utf-8")
    return path


def scaffold_vscode(out: Path) -> list[Path]:
    """Minimal VS Code extension scaffold calling the local API."""
    return [
        _write(out, "package.json", VSCODE_PACKAGE_JSON),
        _write(out, "extension.js", VSCODE_EXTENSION_JS),
        _write(out, "README.md", VSCODE_README),
    ]


def scaffold_browser(out: Path) -> list[Path]:
    """Minimal Manifest V3 browser-extension scaffold calling the local API."""
    return [
        _write(out, "manifest.json", BROWSER_MANIFEST_JSON),
        _write(out, "background.js", BROWSER_BACKGROUND_JS),
        _write(out, "popup.html", BROWSER_POPUP_HTML),
        _write(out, "popup.js", BROWSER_POPUP_JS),
        _write(out, "README.md", BROWSER_README),
    ]
