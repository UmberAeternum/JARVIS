BROWSER_BACKGROUND_JS = """'use strict';
// UMBRA Companion service worker - relays popup queries to the local API.
chrome.runtime.onMessage.addListener((msg, _sender, sendResponse) => {
  if (msg && msg.kind === 'umbra-chat') {
    chrome.storage.local.get({ port: 8775, token: '' }, (cfg) => {
      fetch('http://127.0.0.1:' + cfg.port + '/chat', {
        method: 'POST',
        headers: { 'X-Jarvis-Token': cfg.token, 'Content-Type': 'application/json' },
        body: JSON.stringify({ text: msg.text }),
      })
        .then((r) => r.json())
        .then((data) => sendResponse(data))
        .catch((exc) => sendResponse({ error: 'API offline - run jarvis serve --api (' + exc.message + ')' }));
    });
    return true; // async response
  }
  return false;
});
"""

