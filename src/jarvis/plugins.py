BROWSER_POPUP_JS = """'use strict';
// UMBRA Companion popup - sends the query through the service worker.
const log = document.getElementById('log');
function append(text) { log.textContent += '\\n' + text; log.scrollTop = log.scrollHeight; }

function send() {
  const field = document.getElementById('text');
  const text = field.value.trim();
  if (!text) return;
  field.value = '';
  append('YOU: ' + text);
  chrome.runtime.sendMessage({ kind: 'umbra-chat', text: text }, (data) => {
    append('J: ' + ((data && (data.reply || data.error)) || 'no response'));
  });
}
document.getElementById('send').addEventListener('click', send);
document.getElementById('text').addEventListener('keydown', (e) => {
  if (e.key === 'Enter') send();
});
"""

