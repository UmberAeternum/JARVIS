VSCODE_EXTENSION_JS = """'use strict';
// UMBRA Companion - minimal VS Code extension calling the local UMBRA API.
// Requires: jarvis serve --api  (loopback only; token via settings).
const vscode = require('vscode');
const http = require('http');

function ask(port, token, text) {
  return new Promise((resolve, reject) => {
    const body = JSON.stringify({ text });
    const req = http.request(
      {
        host: '127.0.0.1', port, path: '/chat', method: 'POST',
        headers: { 'X-Jarvis-Token': token, 'Content-Type': 'application/json',
                   'Content-Length': Buffer.byteLength(body) },
      },
      (res) => {
        let data = '';
        res.on('data', (chunk) => { data += chunk; });
        res.on('end', () => {
          try { resolve(JSON.parse(data)); } catch (e) { reject(e); }
        });
      }
    );
    req.on('error', reject);
    req.write(body);
    req.end();
  });
}

function activate(context) {
  const disposable = vscode.commands.registerCommand('umbra.ask', async () => {
    const config = vscode.workspace.getConfiguration('umbra');
    const port = config.get('port', 8775);
    const token = config.get('token', '');
    if (!token) {
      vscode.window.showErrorMessage('UMBRA: set umbra.token to your API token (jarvis api token rotate).');
      return;
    }
    const text = await vscode.window.showInputBox({ prompt: 'Ask UMBRA' });
    if (!text) return;
    try {
      const data = await ask(port, token, text);
      if (data.reply) { vscode.window.showInformationMessage(data.reply); }
      else { vscode.window.showErrorMessage('UMBRA: ' + (data.error || 'no response')); }
    } catch (exc) {
      vscode.window.showErrorMessage('UMBRA API unreachable - run jarvis serve --api (' + exc.message + ')');
    }
  });
  context.subscriptions.push(disposable);
}

function deactivate() {}

module.exports = { activate, deactivate };
"""

